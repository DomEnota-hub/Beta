    fun articleById(id: String): KnowledgeArticle? = allArticles.firstOrNull { it.id == id }

    fun search(query: String, category: String): List<KnowledgeArticle> {
        val q = query.trim().lowercase()
        return knowledgeArticles.filter { article ->
            val categoryMatches = category == "Все" || article.category == category
            val textMatches = article.matches(q)
            categoryMatches && textMatches
        }
    }

    fun searchSafety(query: String, category: String): List<KnowledgeArticle> {
        val q = query.trim().lowercase()
        return safetyArticles.filter { article ->
            val categoryMatches = category == "Все" || article.category == category
            val textMatches = article.matches(q)
            categoryMatches && textMatches
        }
    }

    private fun KnowledgeArticle.matches(query: String): Boolean =
        query.isBlank() || listOf(
            title, summary, category, status,
            body.joinToString(" "), tags.joinToString(" ")
        ).joinToString(" ").lowercase().contains(query)

