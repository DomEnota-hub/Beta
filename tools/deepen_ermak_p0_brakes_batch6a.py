def prune_optional_route_back(scenario: dict) -> None:
    graph = scenario["graph"]
    nodes = {n["id"]: n for n in graph["nodes"]}
    queue = deque([graph["startNodeId"]])
    seen: set[str] = set()
    while queue:
        node_id = queue.popleft()
        if node_id in seen:
            continue
        if node_id not in nodes:
            raise SystemExit(f"{scenario['id']}: missing node {node_id}")
        seen.add(node_id)
        node = nodes[node_id]
        if node.get("nextNodeId"):
            queue.append(node["nextNodeId"])
        for choice in node.get("choices", []):
            queue.append(choice["nextNodeId"])
    unreachable = set(nodes) - seen
    unexpected = unreachable - {"not-this-scenario"}
    if unexpected:
        raise SystemExit(f"{scenario['id']}: unexpected unreachable nodes {sorted(unexpected)}")
    if "not-this-scenario" in unreachable:
        graph["nodes"] = [n for n in graph["nodes"] if n["id"] != "not-this-scenario"]


